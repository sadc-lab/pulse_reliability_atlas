"""One-command reproducibility gate for the Pulse Reliability Atlas.

Runs the full local verification pipeline in three stages:

    [1/3] Regenerate every data-derived figure + the traffic-light artefacts
          from the frozen data tree.
    [2/3] Build the npj PDFs (supplement first, then paper) -- best-effort:
          skipped with a clear note if no LaTeX toolchain is on PATH.
    [3/3] Run both claims-ledger audits (monograph ledger + paper crosswalk)
          as a hard gate.

Cross-platform: invoked the same way on the Windows laptop and on CI/Linux.

    uv run python scripts/verify.py      # or:  make verify

Exit status is non-zero if any figure script errors or either audit FAILs.
The PDF build is best-effort and never fails the run when the TeX toolchain
is absent (it does fail if the toolchain is present but a build breaks).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PY = sys.executable

# Figure / data-artefact generators that are data-derived and live in the repo.
# Matplotlib stamps wall-clock time into every PDF it writes, so two runs of the
# same generator over the same frozen data produce byte-different files that are
# pixel-identical. That made this gate self-defeating: running it always left the
# tracked figure PDFs modified, so the command that demonstrates reproducibility
# was itself the reason `git status` was never clean.
#
# matplotlib honours SOURCE_DATE_EPOCH for the PDF CreationDate. Pinning it makes
# figure output deterministic: verified 2026-08-04 by regenerating the same
# figure twice and comparing with cmp -- bit-identical.
#
# The value is arbitrary but must stay FIXED; changing it rewrites every tracked
# figure. It is the preregistration lock, 2026-04-22 18:05:08 -0400, chosen only
# because it is a date this repository already treats as immovable.
#
# Caveat: this pins the environment of THIS script. Running a generator directly,
# or through `make figures`, still produces a timestamped PDF. verify.py is the
# canonical path.
REPRODUCIBLE_EPOCH = "1776895508"
# FORCE_SOURCE_DATE is required by pdfTeX specifically: unlike matplotlib, it
# IGNORES SOURCE_DATE_EPOCH unless this is set, and stamps a wall-clock
# /CreationDate instead. That is what kept fig00_study_design.pdf -- a pdflatex
# figure, not a matplotlib one -- outside this gate until 2026-08-14. Verified
# on that date: with both variables set, two successive runs produce
# byte-identical PDFs.
REPRODUCIBLE_ENV = {
    **os.environ,
    "SOURCE_DATE_EPOCH": REPRODUCIBLE_EPOCH,
    "FORCE_SOURCE_DATE": "1",
}

# Comments give the RENDERED figure number, resolved from build/*.aux, not the
# filename stem. The two drift apart: fig00_study_design was inserted as
# Figure 1 on 2026-06-24 and shifted every later npj figure by one, and the
# supplement's figure files are named after the SECTION that hosts them, so
# fig_s4_vt_waveform renders as Figure S3 and fig_s3_hyperoxia as Figure S4.
# Corrected 2026-08-04; every number below was read out of the .aux.
FIGURE_SCRIPTS = [
    "scripts/make_figures.py",          # monograph figure set -> figures/
    "scripts/make_fig00_study_design.py",  # npj Figure 1 (study-design flowchart).
                                        # Added 2026-08-14: it was missing, so the
                                        # gate never regenerated the paper's first
                                        # figure. It is a pdflatex + pymupdf
                                        # generator, which is why FORCE_SOURCE_DATE
                                        # above and the pymupdf dependency both
                                        # had to be settled first.
    "scripts/make_paper_fig01.py",      # npj Figure 2 (reliability traffic-light)
    "scripts/make_paper_fig02.py",      # npj Figure 3 (Morris mu* heatmaps, 6 panels)
    "scripts/make_paper_fig03.py",      # npj Figure 4 (actionable corrections)
    "scripts/make_paper_fig04.py",      # npj Figure 5 (sex / blood-volume)
    "scripts/make_supp_fig_s1.py",      # npj Figure S1 (continuous severity)
    "scripts/make_supp_fig_s3.py",      # npj Figure S4 (hyperoxia convergence)
    "scripts/make_supp_fig_s4.py",      # npj Figure S3 (Vt waveform)
    "scripts/make_supp_fig_s5_decomposition.py",  # npj Figure S5 (what the
                                        # composite colour compresses)
    "scripts/export_traffic_light.py",  # reliability traffic-light CSV + JSON
]

# Figures whose generator writes under a DIFFERENT name than the manuscript
# includes, so the tracked npj copy must be propagated once the generator has
# run. Source -> destination, both repo-relative.
#
# This replaces a MISSING_GENERATORS list, emptied 2026-08-16. That list held
# fig_s2_spearman.pdf and asserted it was "generated by no script here, which
# was confirmed by grepping every file under scripts/". The assertion was false,
# and it was the SECOND time this list carried that exact error: the same block
# records fig01_traffic_light.pdf sitting here for the same reason until
# 2026-08-04. Commit b3caa1c had already diagnosed the cause on 2026-07-28 --
# "I had searched for a name instead of searching for the thing" -- because
# scripts/make_figures.py::fig_h4_spearman() writes
# figures/fig05_h4_spearman_mu_star.pdf, and the npj figure is that same file
# under another name. preprint_npj/README_FIGURES.md named the generator
# correctly in its own table throughout.
#
# The real gap was never the generator: it was that the COPY was unscripted. A
# one-off md5sum in b3caa1c confirmed the twins matched that day, but nothing
# re-measured them afterwards, so they drifted at 94d19c2 when the tracked
# figures were rewritten under SOURCE_DATE_EPOCH and the npj copy was left
# behind. The drift was metadata only -- verified 2026-08-16 as pixel-identical
# at 150 dpi, same 46 text tokens, same 42 vector ops, differing solely in
# /CreationDate -- but it meant the published figure sat outside the
# byte-reproducibility invariant that covers every other tracked figure.
# Copying here makes the lockstep an invariant instead of an observation.
FIGURE_COPIES = {
    "figures/fig05_h4_spearman_mu_star.pdf":
        "preprint_npj/figures/fig_s2_spearman.pdf",
}

# Build order matters: supplement first so paper.tex can read supplement.aux
# for xr-hyper cross-document references (mirrors preprint_npj/build_npj.ps1).
LATEX_DOCS = ["supplement", "paper"]


def _run(cmd, cwd=REPO, quiet=False):
    if not quiet:
        print(f"    $ {' '.join(str(c) for c in cmd)}")
    kw = {"cwd": str(cwd), "env": REPRODUCIBLE_ENV}
    if quiet:
        kw["stdout"] = subprocess.DEVNULL
        kw["stderr"] = subprocess.DEVNULL
    return subprocess.run(cmd, **kw).returncode


def regen_figures() -> list[str]:
    print("\n[1/3] Regenerating figures + data artefacts from frozen data ...")
    failed = []
    for script in FIGURE_SCRIPTS:
        print(f"  - {script}")
        if _run([PY, script], quiet=True) != 0:
            print(f"    FAIL: {script} exited non-zero")
            failed.append(script)
    for src, dst in FIGURE_COPIES.items():
        s, d = REPO / src, REPO / dst
        if not s.exists():
            print(f"    FAIL: {src} was not produced, cannot propagate to {dst}")
            failed.append(src)
            continue
        shutil.copyfile(s, d)
        print(f"  - propagated {src} -> {dst}")
    return failed


def build_pdfs():
    print("\n[2/3] Building npj PDFs (best-effort) ...")
    if not (shutil.which("pdflatex") and shutil.which("bibtex")):
        print("  SKIP: pdflatex/bibtex not on PATH -- install TeX Live or MiKTeX")
        print("        to build PDFs locally. (Stage skipped, not failed.)")
        return None
    npj = REPO / "preprint_npj"
    (npj / "build").mkdir(exist_ok=True)
    ok = True
    for stem in LATEX_DOCS:
        if not (npj / f"{stem}.tex").exists():
            print(f"  SKIP: {stem}.tex not present.")
            continue
        print(f"  - building {stem}.pdf (pdflatex x3 + bibtex)")
        pdflatex = ["pdflatex", "-interaction=nonstopmode", "-output-directory=build", f"{stem}.tex"]
        _run(pdflatex, cwd=npj, quiet=True)
        _run(["bibtex", f"build/{stem}"], cwd=npj, quiet=True)
        _run(pdflatex, cwd=npj, quiet=True)
        _run(pdflatex, cwd=npj, quiet=True)
        pdf = npj / "build" / f"{stem}.pdf"
        if pdf.exists():
            print(f"    OK -> {pdf.relative_to(REPO)} ({pdf.stat().st_size} bytes)")
        else:
            print(f"    FAIL: {stem}.pdf not produced (see preprint_npj/build/{stem}.log)")
            ok = False
    return ok


def run_audits() -> bool:
    print("\n[3/3] Running claims-ledger audits (hard gate) ...")
    both_ok = True
    for label, args in [
        ("monograph ledger", ["scripts/audit_claims.py"]),
        ("paper crosswalk sync", ["scripts/audit_claims.py", "--check-paper-sync"]),
    ]:
        res = subprocess.run([PY, *args], cwd=str(REPO), capture_output=True, text=True)
        for line in res.stdout.splitlines():
            if "Anchors verified" in line or "Sync check" in line:
                print(f"  [{label}] {line.strip().replace('*', '')}")
        if res.returncode != 0:
            both_ok = False
            print(f"  FAIL: {label} audit reported a FAIL. Discrepancies:")
            grab = False
            for line in res.stdout.splitlines():
                if line.startswith("## Discrepancies"):
                    grab = True
                elif line.startswith("## ") and grab:
                    break
                if grab and line.startswith("|"):
                    print(f"    {line}")
    return both_ok


def main() -> int:
    print("=" * 70)
    print("Pulse Reliability Atlas -- reproducibility verification")
    print("=" * 70)

    fig_failed = regen_figures()
    pdf_ok = build_pdfs()
    audits_ok = run_audits()

    print("\n" + "=" * 70)
    print("SUMMARY")
    # Since 2026-08-16 every tracked figure in both manuscripts is regenerated
    # here, so a bare "OK" no longer overstates. The qualifier this line used to
    # carry existed because one figure was believed to have no generator; that
    # belief was wrong (see FIGURE_COPIES) and the list is now empty.
    print(f"  figures : {'FAIL (' + ', '.join(fig_failed) + ')' if fig_failed else 'OK'}")
    print(f"  pdfs    : {'SKIPPED (no TeX toolchain)' if pdf_ok is None else ('OK' if pdf_ok else 'FAIL')}")
    print(f"  audits  : {'OK' if audits_ok else 'FAIL'}")
    print("=" * 70)

    failed = bool(fig_failed) or (pdf_ok is False) or (not audits_ok)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
