#!/usr/bin/env python3
"""Build the study-design flowchart (paper Figure 1) as a standalone figure.

Why this exists
---------------
The flowchart used to live inline in `preprint_npj/paper.tex` as a raw
`tikzpicture`. That caused two defects at once:

1. Pinned with `[H]` immediately after the full-page Table 1, it had nowhere to
   go and overflowed the page by 410 pt -- the diagram was cut off mid-flow and
   its caption never rendered at all. `[H]` does not negotiate: if the float
   does not fit, LaTeX prints it off the page rather than moving it.
2. Pandoc cannot render TikZ, so the figure was simply absent from
   `paper.docx`, silently, while every other figure came through.

Externalising it fixes both: the PDF build gets a sized `\\includegraphics`
that behaves like any other float, and the DOCX route picks up the PNG twin
through `docx_pdf_to_png.lua` like every other figure.

What it does
------------
Extracts the `tikzpicture` verbatim from `paper.tex` (never retyped, so the
figure cannot drift from its source), wraps it in a `standalone` document whose
`\\textwidth` is pinned to the sn-jnl body width so the `text width=0.66\\textwidth`
nodes wrap exactly as they did in the paper, compiles it to PDF, and rasterises
the PNG twin the .docx build needs.

Usage:  uv run python scripts/make_fig00_study_design.py
"""

from __future__ import annotations

import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAPER = ROOT / "preprint_npj" / "paper.tex"
FIGDIR = ROOT / "preprint_npj" / "figures"
STEM = "fig00_study_design"

# sn-jnl body width, read from the built paper.log (\textwidth=372.0pt). The
# nodes size themselves as 0.66\textwidth, so this value decides where the box
# labels wrap; guessing it wrong silently reflows the figure.
TEXTWIDTH_PT = 372.0


def extract_tikz(source: pathlib.Path) -> str | None:
    """Pull the tikzpicture out of paper.tex, or None once it has moved out.

    The first run migrates the picture; every run after that finds nothing left
    in paper.tex and falls back to the externalised source, so this script is
    idempotent rather than one-shot.
    """
    lines = source.read_text(encoding="utf-8").split("\n")
    try:
        start = next(i for i, ln in enumerate(lines) if ln.strip().startswith(r"\begin{tikzpicture}"))
        end = next(i for i, ln in enumerate(lines) if ln.strip() == r"\end{tikzpicture}")
    except StopIteration:
        return None
    return "\n".join(lines[start:end + 1])


def main() -> int:
    tex = FIGDIR / (STEM + ".tex")
    tikz = extract_tikz(PAPER)

    if tikz is None:
        if not tex.exists():
            sys.exit("no tikzpicture in paper.tex and no %s to fall back on" % tex.name)
        prev = tex.read_text(encoding="utf-8").split("\n")
        s = next(i for i, ln in enumerate(prev) if ln.strip().startswith(r"\begin{tikzpicture}"))
        e = next(i for i, ln in enumerate(prev) if ln.strip() == r"\end{tikzpicture}")
        tikz = "\n".join(prev[s:e + 1])
        print("paper.tex no longer holds the picture; rebuilding from %s" % tex.name)

    doc = "\n".join([
        r"% Generated by scripts/make_fig00_study_design.py -- do not hand-edit.",
        r"% The tikzpicture below is copied verbatim from preprint_npj/paper.tex.",
        r"\documentclass[border=6pt]{standalone}",
        r"\usepackage{tikz}",
        r"\usetikzlibrary{arrows.meta,positioning}",
        # npj asks for sans-serif lettering, in one typeface across all figures.
        # A standalone TikZ document otherwise inherits the LaTeX serif default,
        # which made this the only serif figure in the paper. Font only -- the
        # tikzpicture body is still copied verbatim from paper.tex.
        r"\renewcommand{\familydefault}{\sfdefault}",
        r"\setlength{\textwidth}{%.1fpt}" % TEXTWIDTH_PT,
        r"\begin{document}",
        tikz,
        r"\end{document}",
        "",
    ])
    tex = FIGDIR / (STEM + ".tex")
    tex.write_text(doc, encoding="utf-8")
    print("wrote %s (%d bytes)" % (tex.name, tex.stat().st_size))

    if shutil.which("pdflatex") is None:
        sys.exit("pdflatex not on PATH")
    proc = subprocess.run(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex.name],
        cwd=FIGDIR, capture_output=True, text=True,
    )
    pdf = FIGDIR / (STEM + ".pdf")
    if proc.returncode != 0 or not pdf.exists():
        print(proc.stdout[-2000:])
        sys.exit("pdflatex failed on %s" % tex.name)

    try:
        import fitz
    except ImportError:
        sys.exit("pymupdf needed for the PNG twin: uv run --with pymupdf python %s" % __file__)

    page = fitz.open(pdf)[0]
    # 300 dpi matches what build_npj.ps1 asks pdftoppm for on the other figures.
    page.get_pixmap(dpi=300).save(FIGDIR / (STEM + ".png"))
    print("pdf  %.1f x %.1f pt" % (page.rect.width, page.rect.height))
    print("png  %d bytes" % (FIGDIR / (STEM + ".png")).stat().st_size)

    for junk in (".aux", ".log"):
        (FIGDIR / (STEM + junk)).unlink(missing_ok=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
