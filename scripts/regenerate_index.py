#!/usr/bin/env python3
"""Regenerate experiments_log/INDEX.md from YAML frontmatter in every experiment file.

Runs as a pre-commit hook. Dependency-free (stdlib only) so it works on a fresh
clone without needing `uv sync` first.

Conventions enforced:
- Experiment files live in experiments_log/{santino,shared}/
- Each file starts with a YAML frontmatter block delimited by '---' lines.
- The body's first '# ' heading is used as the title in the index.

The script is idempotent: running it twice produces byte-identical output.
If INDEX.md is unchanged, git add is a no-op.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG_DIR = ROOT / "experiments_log"
INDEX_FILE = LOG_DIR / "INDEX.md"

FRONTMATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)

AUTHOR_FOLDERS = [
    ("Santino", "santino"),
    ("Shared (ensemble)", "shared"),
]


def parse_frontmatter(text: str) -> dict | None:
    """Parse a simple YAML-like frontmatter block. Returns None if missing."""
    match = FRONTMATTER_RE.match(text)
    if not match:
        return None
    data: dict = {}
    for raw_line in match.group(1).splitlines():
        line = raw_line.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        # Strip surrounding quotes.
        if (value.startswith('"') and value.endswith('"')) or (
            value.startswith("'") and value.endswith("'")
        ):
            value = value[1:-1]
        # Parse inline list: [a, b, c]
        if value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            value = [v.strip().strip('"').strip("'") for v in inner.split(",") if v.strip()]
        data[key] = value
    return data


def first_heading(text: str) -> str:
    """Return the first '# ' heading found after the frontmatter, or a fallback."""
    body = FRONTMATTER_RE.sub("", text, count=1)
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip()
    return "(no title)"


def collect_entries() -> list[dict]:
    """Walk the experiments_log folders and collect every valid entry."""
    entries: list[dict] = []
    for _, folder in AUTHOR_FOLDERS:
        folder_path = LOG_DIR / folder
        if not folder_path.exists():
            continue
        for md_file in sorted(folder_path.glob("*.md")):
            text = md_file.read_text(encoding="utf-8")
            fm = parse_frontmatter(text)
            if fm is None:
                # Skip files without frontmatter (e.g. accidental notes).
                continue
            fm["_path"] = md_file.relative_to(LOG_DIR).as_posix()
            fm["_folder"] = folder
            fm["_title"] = first_heading(text)
            entries.append(fm)
    return entries


def _as_list(value) -> list[str]:
    if value is None or value == "":
        return []
    if isinstance(value, list):
        return [str(v) for v in value if str(v).strip()]
    return [str(value)]


def render_index(entries: list[dict]) -> str:
    """Produce the full INDEX.md content."""
    lines: list[str] = [
        "# PulseProbe — Experiments Index",
        "",
        "**Auto-generated by `scripts/regenerate_index.py` — do not edit by hand.**",
        "",
        "This file is rebuilt from the YAML frontmatter of every entry in",
        "`santino/` and `shared/`. To update it, edit the experiment",
        "and recommit — the pre-commit hook regenerates and stages this file.",
        "",
        f"Total entries: **{len(entries)}**",
        "",
    ]

    # --- Section 1: all experiments, newest first --------------------------
    lines.append("## All experiments (newest first)")
    lines.append("")
    if not entries:
        lines.append("_No entries yet._")
        lines.append("")
    else:
        lines.append("| ID | Date | Author | Status | Title |")
        lines.append("|---|---|---|---|---|")
        for e in sorted(
            entries,
            key=lambda e: (str(e.get("date", "")), str(e.get("id", ""))),
            reverse=True,
        ):
            lines.append(
                f"| `{e.get('id', '?')}` "
                f"| {e.get('date', '')} "
                f"| {e.get('author', '')} "
                f"| {e.get('status', '')} "
                f"| [{e['_title']}]({e['_path']}) |"
            )
        lines.append("")

    # --- Section 2: grouped by author/folder ------------------------------
    for label, folder in AUTHOR_FOLDERS:
        subset = [e for e in entries if e["_folder"] == folder]
        if not subset:
            continue
        lines.append(f"## {label}")
        lines.append("")
        for e in sorted(subset, key=lambda e: str(e.get("id", ""))):
            tags = _as_list(e.get("tags"))
            tag_str = f" — _{', '.join(tags)}_" if tags else ""
            lines.append(
                f"- `{e.get('id', '?')}` "
                f"({e.get('date', '')}, {e.get('status', '')}) "
                f"— [{e['_title']}]({e['_path']}){tag_str}"
            )
        lines.append("")

    # --- Section 3: by tag ------------------------------------------------
    tag_map: dict[str, list[dict]] = {}
    for e in entries:
        for tag in _as_list(e.get("tags")):
            tag_map.setdefault(tag, []).append(e)
    if tag_map:
        lines.append("## By tag")
        lines.append("")
        for tag in sorted(tag_map):
            lines.append(f"### `{tag}`")
            for e in sorted(tag_map[tag], key=lambda e: str(e.get("id", ""))):
                lines.append(f"- `{e.get('id', '?')}` — [{e['_title']}]({e['_path']})")
            lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    if not LOG_DIR.exists():
        # Nothing to index. Do not fail — pre-commit hook should be a no-op here.
        return 0

    entries = collect_entries()
    new_content = render_index(entries)

    old_content = INDEX_FILE.read_text(encoding="utf-8") if INDEX_FILE.exists() else ""
    if new_content == old_content:
        return 0

    INDEX_FILE.write_text(new_content, encoding="utf-8")

    # Stage the updated index so it lands in the same commit.
    # Errors here are non-fatal: the file is still written, the user can stage manually.
    try:
        subprocess.run(
            ["git", "add", str(INDEX_FILE)],
            check=False,
            capture_output=True,
            cwd=ROOT,
        )
    except FileNotFoundError:
        # git not on PATH — rare, but do not block the write.
        pass

    return 0


if __name__ == "__main__":
    sys.exit(main())
